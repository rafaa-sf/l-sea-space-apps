<script setup>
/**
 * Main viewport: renders the moon scene in 3D (lazy-loaded Three.js) or its
 * top-down 2D camera preset, with the automatic Canvas 2D fallback when WebGL
 * is unavailable, data-source badges, layer status and a keyboard/screen-reader
 * friendly wrapper.
 */
import { computed, nextTick, onBeforeUnmount, onMounted, ref, watch } from 'vue'
import { useI18n } from 'vue-i18n'
import { actions, compareSites, selectedSite, state } from './composables/useAppState.js'
import { getCompute } from './composables/useCompute.js'
import { DEM_REGIONS } from './composables/useData.js'
import { lonLatToPlanarMeters } from '../render/geo.js'
import { detectWebgl } from '../render/webgl.js'
import { siteDisplayName, sourceLabelKey } from './composables/labels.js'
import { formatNumber } from './composables/format.js'

const { t, te, locale } = useI18n()

const canvasRef = ref(null)
const stageRef = ref(null)
const canvasKey = ref(0)
const mode = ref('initializing')
const initializing = ref(true)
const webgl = ref(state.system.webgl)
const note = ref(null)
const scaleInfo = ref(null)
const zoomRatio = ref(0.5)

let api = null
let compute = null
let recreateToken = 0
let watchers = []
let settleTimer = null
let pointerTimer = null
let stageObserver = null

const labels = computed(() => ({
  sun: t('viewport.sun'),
  earth: t('viewport.earth'),
  scaleKm: t('viewport.scaleKm', { km: 50 }),
}))

const terrainBounds = computed(() => {
  const terrain = state.terrain
  if (!terrain || !Number.isFinite(Number(terrain.minX))) return null
  return {
    minX: Number(terrain.minX),
    maxX: Number(terrain.maxX),
    minY: Number(terrain.minY),
    maxY: Number(terrain.maxY),
    datum: Number(terrain.datum ?? terrain.referenceRadiusM ?? 1737400),
  }
})

/** Sites inside the loaded DEM extent; outside sites are hidden and flagged. */
const sitesInRegion = computed(() => {
  const bounds = terrainBounds.value
  if (!bounds) return state.sites
  return state.sites.filter((site) => {
    const point = lonLatToPlanarMeters(site.lat, site.lon, bounds.datum)
    return point.x >= bounds.minX && point.x <= bounds.maxX && point.y >= bounds.minY && point.y <= bounds.maxY
  })
})
const sitesOutsideCount = computed(() => Math.max(0, state.sites.length - sitesInRegion.value.length))
const sceneSites = computed(() => {
  const list = [...sitesInRegion.value]
  const zoneSite = state.landingZoneSite
  if (zoneSite && !list.some((site) => site.id === zoneSite.id)) {
    const bounds = terrainBounds.value
    const inside =
      !bounds ||
      (() => {
        const point = lonLatToPlanarMeters(zoneSite.lat, zoneSite.lon, bounds.datum)
        return point.x >= bounds.minX && point.x <= bounds.maxX && point.y >= bounds.minY && point.y <= bounds.maxY
      })()
    if (inside) list.push({ ...zoneSite, displayName: zoneSite.name })
  }
  return list.map((site) => ({ ...site, displayName: site.displayName ?? siteDisplayName(t, te, site) }))
})

function regionLabel(region) {
  if (region.id === 'south-pole-875s-20m') return t('dem.highDetail')
  if (region.id === 'south-pole-80s-80m') return t('dem.wide')
  const parsePair = (value) => {
    if (typeof value !== 'string') return null
    const parts = value.trim().split(/[\s,]+/).map(Number)
    return parts.length >= 2 && Number.isFinite(parts[0]) && Number.isFinite(parts[1]) ? parts : null
  }
  const flat = region.boundsM
  const lower = parsePair(flat?.lower) ?? (Number.isFinite(Number(flat?.minX)) && Number.isFinite(Number(flat?.minY)) ? [Number(flat.minX), Number(flat.minY)] : null)
  const upper = parsePair(flat?.upper) ?? (Number.isFinite(Number(flat?.maxX)) && Number.isFinite(Number(flat?.maxY)) ? [Number(flat.maxX), Number(flat.maxY)] : null)
  if (!lower || !upper) return region.id
  const minX = Math.min(lower[0], upper[0]) / 1000
  const maxX = Math.max(lower[0], upper[0]) / 1000
  const minY = Math.min(lower[1], upper[1]) / 1000
  const maxY = Math.max(lower[1], upper[1]) / 1000
  const width = Math.round(maxX - minX)
  const height = Math.round(maxY - minY)
  const resolution = Number(region.pixelSizeM)
  const resolutionLabel = Number.isFinite(resolution) ? formatNumber(resolution, 0) : '?'
  // Built-in area presets generated by the local LOLA downloader (100/200/300/400 km).
  if (/^south-pole-\d+km-\d+px$/.test(region.id)) {
    return t('dem.area', { width, height, resolution: resolutionLabel })
  }
  return t('dem.customFull', {
    width,
    height,
    resolution: Number.isFinite(resolution) ? formatNumber(resolution, 0) : '?',
    minX: formatNumber(minX, 1),
    maxX: formatNumber(maxX, 1),
    minY: formatNumber(minY, 1),
    maxY: formatNumber(maxY, 1),
  })
}

function regionSpanM(region) {
  const bounds = region.boundsM
  if (bounds && Number.isFinite(Number(bounds.minX)) && Number.isFinite(Number(bounds.maxX))) {
    return Math.max(Number(bounds.maxX) - Number(bounds.minX), Number(bounds.maxY) - Number(bounds.minY))
  }
  return Number(region.width ?? 0) * Number(region.pixelSizeM ?? 0)
}

const demRegions = computed(() => {
  const indexed = Array.isArray(state.data.terrainIndex) ? state.data.terrainIndex : []
  const list = indexed.length ? indexed : DEM_REGIONS
  return list
    .map((region) => ({ ...region, label: regionLabel(region) }))
    .sort((a, b) => regionSpanM(a) - regionSpanM(b))
})

const selectedName = computed(() => siteDisplayName(t, te, selectedSite.value) || t('common.none'))

const modeOptions = computed(() => [
  { value: '3d', label: t('viewport.mode.threeD') },
  { value: '2d', label: t('viewport.mode.twoD') },
])

/** Badge reflects the selected view mode on the Three.js scene, not the preset id. */
const rendererBadge = computed(() => {
  if (mode.value === '3d') return state.system.viewMode === '2d' ? t('viewport.mode.twoD') : t('viewport.mode.threeD')
  if (mode.value === '2d') return t('viewport.mode.twoD')
  return t('common.loading')
})

const fallbackReason = computed(() => {
  // The banner only exists for the automatic Canvas 2D fallback (no WebGL or a
  // failed 3D creation); the top-down 2D view is not a fallback.
  if (mode.value !== '2d') return null
  if (webgl.value && webgl.value.ok === false) return t(`viewport.fallback.reason.${webgl.value.reason === 'no-context' ? 'noContext' : 'unavailable'}`)
  return note.value ? t('viewport.fallback.reason.error') : null
})

const terrainBadge = computed(() => t(sourceLabelKey(state.data.terrainSource, 'terrain')))
const isRectangular = computed(() => Boolean(state.terrain && Number.isFinite(Number(state.terrain.minX))))
const terrainLayout = computed(() => (isRectangular.value ? 'rectangular' : 'polar'))
const terrainExtent = computed(() => {
  const terrain = state.terrain
  if (!isRectangular.value || !terrain) return ''
  return [terrain.minX, terrain.minY, terrain.maxX, terrain.maxY].map((value) => Number(value).toFixed(1)).join(',')
})
const markersAnchored = computed(() => (state.analysis.ready && state.selectedSiteId ? 'true' : 'false'))
const demRegionId = computed(() => state.data.terrainRegionId ?? demRegions.value[0]?.id ?? '')
const ephemerisBadge = computed(() => t(sourceLabelKey(state.data.ephemerisSource, 'ephemeris')))

/** Altitude of the selected point and, when comparing, of each compared site. */
const altitudeEntries = computed(() => {
  const selected = selectedSite.value
  const sampleM = (site) => {
    if (!site) return null
    const candidate = site.id === selected?.id ? state.analysis.siteElevationM : site.elevationM
    if (Number.isFinite(Number(candidate))) return Number(candidate)
    if (compute && state.terrain) {
      const sampled = compute.sampleElevation(state.terrain, site.lat, site.lon)
      return Number.isFinite(Number(sampled)) ? Number(sampled) : null
    }
    return null
  }
  const rows = []
  if (selected) {
    rows.push({
      id: selected.id,
      label: t('viewport.selectedAltitude'),
      name: siteDisplayName(t, te, selected),
      elevationM: sampleM(selected),
      color: '#6ee7ff',
    })
  }
  for (const site of compareSites.value) {
    if (site.id === selected?.id) continue
    rows.push({
      id: site.id,
      label: siteDisplayName(t, te, site),
      name: siteDisplayName(t, te, site),
      elevationM: sampleM(site),
      color: '#ffb454',
    })
  }
  return rows.filter((row) => row.elevationM !== null)
})


function niceScaleMeters(target) {
  const safe = Math.max(1, target)
  const exponent = Math.floor(Math.log10(safe))
  const base = safe / 10 ** exponent
  const nice = base >= 5 ? 5 : base >= 2 ? 2 : 1
  return nice * 10 ** exponent
}

/**
 * Scale bar from the renderer's view info: the visible ground width at the
 * target plane is `2 * distance * tan(fov/2) / unitsPerMeter`; pick a round
 * metre value close to 1/6 of that width and size the bar proportionally.
 */
function updateScaleBar(info) {
  if (!info || !Number.isFinite(info.visibleMeters) || info.visibleMeters <= 0) return
  const meters = niceScaleMeters(info.visibleMeters / 6)
  const px = Math.max(36, Math.min(220, (meters / info.visibleMeters) * info.widthPx))
  const metersPerPixel = info.visibleMeters / Math.max(1, info.widthPx)
  const label = meters >= 1000 ? `${formatNumber(meters / 1000, 0)} km` : `${formatNumber(meters, 0)} m`
  scaleInfo.value = { meters, px, label, metersPerPixel }
}

/** Coalesce rapid terrain clicks: the readout updates at once, the heavy
 * site selection/analysis is debounced to the last clicked point. */
function queuePointerPin(coordinates) {
  actions.setPointerLocation(coordinates)
  if (pointerTimer) clearTimeout(pointerTimer)
  pointerTimer = setTimeout(() => {
    pointerTimer = null
    actions.pinPointerSite(coordinates)
  }, 220)
}

function cancelPointerPin() {
  if (pointerTimer) {
    clearTimeout(pointerTimer)
    pointerTimer = null
  }
}

function rendererOptions() {
  return {
    labels: labels.value,
    sampleElevation: (lat, lon) => (compute && state.terrain ? compute.sampleElevation(state.terrain, lat, lon) : 0),
    terrainStats: (terrain) => (compute ? compute.terrainStats(terrain) : { minM: 0, maxM: 1 }),
    onPickSite: (id) => {
      cancelPointerPin()
      actions.selectSite(id)
    },
    onPickLocation: queuePointerPin,
    onLayerStatus: (id, status) => {
      actions.setLayerStatus(id, status)
    },
    onViewChange: (info) => updateScaleBar(info),
  }
}

function pushTerrain() {
  if (!api) return
  // Rectangular LOLA DEM extents (planar) when available; legacy lat/lon grid
  // only for the synthetic fallback path.
  const renderTerrain =
    state.terrain && Number.isFinite(Number(state.terrain.minX)) ? state.terrain : state.viewTerrain
  if (!renderTerrain) return
  api.setTerrain(renderTerrain)
  // Rebuild every overlay against the NEW projection immediately after the
  // grid, before returning (region switch ordering).
  pushSites()
  pushEnvironment()
  pushLayers()
}

function pushSites() {
  if (!api) return
  api.setSites(sceneSites.value, {
    selectedId: state.selectedSiteId,
    compareIds: state.compareSiteIds,
  })
}

function pushEnvironment() {
  if (!api) return
  api.setSunDirection(state.analysis.sun, state.analysis.sunVisible)
  api.setEarthDirection(state.analysis.earth, state.analysis.earthVisible)
  const ray = state.analysis.ray
  api.setRay(
    ray
      ? {
          ...ray,
          azimuth: state.analysis.sun.az,
          elevation: state.analysis.sun.el,
          elevationM: compute && state.terrain ? compute.sampleElevation(state.terrain, ray.lat, ray.lon) : 0,
        }
      : null,
  )
}

function pushLayers() {
  if (!api) return
  const enabled = Object.keys(state.layerEnabled).filter((id) => state.layerEnabled[id])
  api.setLayers(state.layers, enabled)
}

/**
 * Geometry changes (rail drags, vertical split, window resize) can leave the
 * scene's screen-space marker state stale. Debounced re-detect: ask the
 * renderer to resize, then re-run sites/labels/overlays against the current
 * projection (no page reload, camera/selection preserved).
 */
function scheduleMarkerResync() {
  if (settleTimer) clearTimeout(settleTimer)
  settleTimer = setTimeout(() => {
    settleTimer = null
    if (!api) return
    try {
      api.resize?.()
    } catch {
      /* renderer handles its own resize */
    }
    pushSites()
    pushEnvironment()
    pushLayers()
  }, 120)
}

function pushLabels() {
  api?.setLabels(labels.value)
}

function pushAll() {
  pushTerrain()
  pushSites()
  pushEnvironment()
  pushLayers()
  pushLabels()
}

async function destroyRenderer() {
  if (!api) return
  try {
    api.dispose()
  } catch (error) {
    console.warn('[lsea] renderer dispose failed', error)
  }
  api = null
}

async function createRenderer() {
  const token = (recreateToken += 1)
  initializing.value = true
  note.value = null
  await destroyRenderer()
  if (token !== recreateToken) return
  // A canvas element that already holds a WebGL context cannot return a 2D
  // context (and vice versa), so mount a fresh canvas for every renderer.
  canvasKey.value += 1
  await nextTick()
  if (token !== recreateToken) return
  const canvas = canvasRef.value
  if (!canvas) return

  // The Three.js scene always renders when WebGL is available; the 2D view is a
  // camera preset on that same scene, never a second renderer.
  let created = null
  let threeAttempted = false

  if (webgl.value?.ok) {
    threeAttempted = true
    try {
      const { createMoonScene } = await import('../render/moonScene.js')
      if (token !== recreateToken) return
      created = await createMoonScene(canvas, rendererOptions())
      if (token !== recreateToken) {
        created?.dispose?.()
        return
      }
    } catch (error) {
      if (token !== recreateToken) return
      console.warn('[lsea] WebGL scene failed, using the 2D map', error)
      note.value = 'three-failed'
      created = null
    }
  }

  if (!created) {
    if (token !== recreateToken) return
    // Even a failed 3D attempt may have taken a WebGL context on this canvas;
    // never reuse it for the 2D fallback. Mount a fresh canvas for 2D only.
    if (threeAttempted) {
      canvasKey.value += 1
      await nextTick()
      if (token !== recreateToken) return
    }
    const fallbackCanvas = canvasRef.value
    if (!fallbackCanvas) return
    try {
      const { createFallback2D } = await import('../render/fallback2d.js')
      if (token !== recreateToken) return
      created = createFallback2D(fallbackCanvas, rendererOptions())
    } catch (error) {
      if (token !== recreateToken) return
      console.error('[lsea] 2D fallback failed', error)
      note.value = 'fallback-failed'
      initializing.value = false
      mode.value = 'error'
      return
    }
  }

  if (token !== recreateToken) {
    created.dispose()
    return
  }

  api = created
  syncZoom()
  mode.value = created.kind
  actions.setRenderer(created.kind)
  if (created.kind === '3d') applyViewPreset()
  initializing.value = false
  pushAll()
}

/** Apply the selected view mode to the live 3D scene (camera only, no rebuild). */
function syncZoom() {
  if (!api || typeof api.getZoom !== 'function') return
  const value = Number(api.getZoom())
  if (Number.isFinite(value)) zoomRatio.value = Math.min(1, Math.max(0, value))
}

function zoomStep(delta) {
  if (!api || typeof api.zoomBy !== 'function') return
  api.zoomBy(delta)
  syncZoom()
}

function onZoomInput(event) {
  const value = Number(event.target.value) / 100
  zoomRatio.value = Number.isFinite(value) ? value : 0.5
  if (api && typeof api.setZoom === 'function') api.setZoom(zoomRatio.value)
}

function applyViewPreset() {
  const preset = state.system.viewMode === '2d' ? 'top' : 'perspective'
  if (api?.setViewPreset) {
    api.setViewPreset(preset)
    return
  }
  // Canvas 2D fallback already shows the whole map, so nothing to do; with no
  // renderer at all, retry the creation so the selected mode is applied.
  if (!api) createRenderer()
}

function setupWatchers() {
  watchers.push(
    watch(
      () => state.viewTerrain,
      () => {
        pushTerrain()
        pushSites()
        pushEnvironment()
        pushLayers()
      },
    ),
    watch(
      () => [state.sites, state.selectedSiteId, state.compareSiteIds],
      () => pushSites(),
      { deep: false },
    ),
    watch(
      () => state.analysis.updatedAt,
      () => pushEnvironment(),
    ),
    watch(
      () => ({ ...state.layerEnabled }),
      () => pushLayers(),
      { deep: true },
    ),
    watch(
      () => state.layers,
      () => pushLayers(),
      { deep: false },
    ),
    watch(
      () => locale.value,
      () => {
        pushLabels()
        pushSites()
      },
    ),
    watch(
      () => state.system.viewMode,
      () => applyViewPreset(),
    ),
  )
}

function setTerrainRegion(event) {
  actions.setTerrainRegion(event.target.value)
}

function setViewMode(value) {
  if (state.system.viewMode === value) return
  actions.setViewMode(value)
}

function resetView() {
  api?.resetView()
}

function onCanvasKeydown(event) {
  if (event.key !== 'ArrowDown' && event.key !== 'ArrowUp') return
  event.preventDefault()
  const currentIndex = state.sites.findIndex((site) => site.id === state.selectedSiteId)
  const delta = event.key === 'ArrowDown' ? 1 : -1
  const nextIndex = (currentIndex + delta + state.sites.length) % Math.max(1, state.sites.length)
  const nextSite = state.sites[nextIndex]
  if (nextSite) actions.selectSite(nextSite.id)
}

onMounted(async () => {
  compute = await getCompute()
  webgl.value = detectWebgl()
  actions.setWebglStatus(webgl.value)
  await createRenderer()
  setupWatchers()
  if (stageRef.value) {
    stageObserver = new ResizeObserver(() => scheduleMarkerResync())
    stageObserver.observe(stageRef.value)
  }
})

onBeforeUnmount(() => {
  for (const stop of watchers) stop()
  watchers = []
  if (stageObserver) stageObserver.disconnect()
  if (settleTimer) clearTimeout(settleTimer)
  cancelPointerPin()
  destroyRenderer()
})
</script>

<template>
  <section
    class="viewport"
    :class="{ 'is-initializing': initializing }"
    :aria-label="t('viewport.regionLabel')"
    :aria-busy="initializing"
    :data-markers-anchored="markersAnchored"
  >
    <div ref="stageRef" class="viewport__stage">
      <canvas
        :key="canvasKey"
        ref="canvasRef"
        class="viewport__canvas"
        tabindex="0"
        role="img"
        :aria-label="t('viewport.canvasLabel', { site: selectedName })"
        :title="t('viewport.canvasTitle')"
        data-testid="viewport-canvas"
        :data-terrain-layout="terrainLayout"
        :data-terrain-extent="terrainExtent"
        :data-terrain-region="demRegionId"
        :data-sites-visible="String(sitesInRegion.length)"
        :data-sites-outside="String(sitesOutsideCount)"
        data-hillshade-mode="fixed"
        @keydown="onCanvasKeydown"
      />
      <p class="sr-only">{{ t('viewport.keyboardHint') }}</p>

      <div class="viewport__badges">
        <span class="toolbar-badge" :class="mode === '3d' || state.system.renderer === '3d' ? 'is-ok' : 'is-warn'">
          {{ rendererBadge }}
        </span>
        <span class="toolbar-badge" :title="t('viewport.terrainBadgeHint')">{{ terrainBadge }}</span>
        <span class="toolbar-badge" :title="t('viewport.ephemerisBadgeHint')">{{ ephemerisBadge }}</span>
      </div>

      <div class="viewport__controls">
        <label class="dem-select">
          <span class="sr-only">{{ t('dem.title') }}</span>
          <select
            class="input dem-select__control"
            :value="demRegionId"
            data-testid="dem-region-select"
            :aria-label="t('dem.title')"
            :title="t('dem.hint')"
            aria-describedby="dem-region-hint"
            @change="setTerrainRegion"
          >
            <option v-for="region in demRegions" :key="region.id" :value="region.id">{{ region.label }}</option>
          </select>
          <span id="dem-region-hint" class="sr-only">{{ t('dem.hint') }}</span>
        </label>
        <div
          v-if="webgl?.ok !== false"
          class="segmented"
          role="group"
          data-testid="view-mode-toggle"
          :aria-label="t('viewport.modeLabel')"
        >
          <button
            v-for="option in modeOptions"
            :key="option.value"
            type="button"
            class="segmented__button"
            :class="{ 'is-active': state.system.viewMode === option.value }"
            :aria-pressed="state.system.viewMode === option.value"
            @click="setViewMode(option.value)"
          >
            {{ option.label }}
          </button>
        </div>
        <button type="button" class="button button--quiet button--small" :title="t('viewport.resetViewHint')" @click="resetView">
          {{ t('viewport.resetView') }}
        </button>
      </div>

      <div v-if="initializing" class="viewport__overlay">
        <div class="spinner" aria-hidden="true" />
        <p>{{ t('viewport.loadingScene') }}</p>
      </div>

      <div v-else-if="mode === 'error'" class="viewport__overlay viewport__overlay--error" role="alert">
        <p>{{ t('viewport.errorScene') }}</p>
        <button type="button" class="button button--ghost" @click="createRenderer">{{ t('common.retry') }}</button>
      </div>

      <div v-if="note === 'three-failed'" class="viewport__banner viewport__banner--warn" role="status">
        {{ t('viewport.banner.threeFailed') }}
      </div>

      <div v-if="mode === '2d'" class="viewport__banner" role="status">
        <strong>{{ t('viewport.banner.fallbackTitle') }}</strong>
        <span>{{ fallbackReason }}</span>
        <button
          v-if="webgl && webgl.ok"
          type="button"
          class="button button--link"
          @click="setViewMode('3d')"
        >
          {{ t('viewport.banner.try3d') }}
        </button>
      </div>

      <p
        v-if="sitesOutsideCount"
        class="viewport__sites-status"
        :class="{ 'is-2d': mode === '2d' }"
        role="status"
        aria-live="polite"
      >
        {{ t('viewport.sitesOutside', { count: sitesOutsideCount }) }}
      </p>

      <div
        v-if="altitudeEntries.length"
        class="map-altitude"
        data-testid="map-altitude"
        role="status"
        aria-live="polite"
        :aria-label="t('viewport.altitudeTitle')"
      >
        <span class="map-altitude__title">{{ t('viewport.altitudeTitle') }}</span>
        <span v-for="entry in altitudeEntries" :key="entry.id" class="map-altitude__row">
          <span class="map-altitude__dot" :style="{ background: entry.color }" aria-hidden="true" />
          <span class="map-altitude__name" :title="entry.label">{{ entry.name }}</span>
          <span class="map-altitude__value">{{ formatNumber(entry.elevationM, 0) }} m</span>
        </span>
      </div>

      <div class="zoom-bar" role="group" :aria-label="t('viewport.zoomLevel')" data-testid="zoom-bar">
        <button
          type="button"
          class="zoom-bar__button"
          :aria-label="t('viewport.zoomIn')"
          :title="t('viewport.zoomIn')"
          @click="zoomStep(0.1)"
        >
          <svg viewBox="0 0 24 24" aria-hidden="true"><path d="M12 5v14M5 12h14" /></svg>
        </button>
        <input
          class="zoom-bar__range"
          type="range"
          min="0"
          max="100"
          step="1"
          :value="Math.round(zoomRatio * 100)"
          :aria-label="t('viewport.zoomLevel')"
          @input="onZoomInput"
        />
        <button
          type="button"
          class="zoom-bar__button"
